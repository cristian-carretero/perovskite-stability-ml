@st.cache_data(show_spinner=False)
def load_full_pce_history() -> pd.DataFrame:
    """Full-lifecycle PCE per cell from the fleet telemetry (10-min resolution).

    Returns a long-format DataFrame: Timestamp | cell_name | PCE.
    Only daylight samples (POA > threshold) are kept, since PCE is only
    physically meaningful under illumination. This avoids diluting the
    daily median with nighttime zeros.
    """
    fleet = load_global_data()
    if fleet.empty:
        return pd.DataFrame()
    pce_cols = [c for c in fleet.columns if c.lower().startswith("pce_")]
    if not pce_cols:
        return pd.DataFrame()

    # Daylight filter: otherwise 50% of rows would be nighttime zeros and
    # the daily median would be a meaningless mix of both regimes.
    if "POA_Irradiance_W_m2" in fleet.columns:
        fleet = fleet[fleet["POA_Irradiance_W_m2"] > DAYLIGHT_IRRADIANCE_MIN_W_M2]

    frames = []
    for col in pce_cols:
        cell = col.split("_", 1)[1]
        sub = fleet[[col]].dropna().rename(columns={col: "PCE"})
        sub = sub.reset_index()
        sub["Timestamp"] = pd.to_datetime(sub["Timestamp"], utc=True).dt.tz_localize(None)
        sub["cell_name"] = cell
        # Clip to plausible PCE range; negative or > 100% are numerical artifacts.
        sub = sub[(sub["PCE"] >= 0) & (sub["PCE"] <= 100)]
        if not sub.empty:
            frames.append(sub[["Timestamp", "cell_name", "PCE"]])

    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


