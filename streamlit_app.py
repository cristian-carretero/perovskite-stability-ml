@st.cache_data(show_spinner=False)
def load_survival_data() -> pd.DataFrame:
    """Load the per-cell T80 survival summary (produced by 06_jv_mppt_t80_tracker).

    This is a per-cell summary (one row per device), not a time series, so it
    has no 'Timestamp' column. It is normalized to a DataFrame with 'cell_name'
    as a regular column and naive-UTC datetime fields.
    """
    try:
        if SURVIVAL_DATA_PATH.exists():
            df = pd.read_parquet(SURVIVAL_DATA_PATH)
            if "cell_name" not in df.columns:
                df = df.reset_index()
                if "cell_name" not in df.columns and "index" in df.columns:
                    df = df.rename(columns={"index": "cell_name"})
            for col in df.columns:
                if col.endswith("_date"):
                    df[col] = pd.to_datetime(df[col], utc=True, errors="coerce").dt.tz_localize(None)
            return df
    except Exception as exc:
        st.warning(f"Failed to load the survival dataset: {exc}")
    return pd.DataFrame()


